def run_comparison():
    rt, mi = _load_rt()
    cfg = _load_config("room_demo.yaml")
    comparison = _load_config("comparison.yaml")
    root = OUTPUT_DIR / "comparison"
    baseline_x = float(comparison["baseline_panel_center_x_m"])
    moved_x = float(comparison["moved_panel_center_x_m"])
    baseline_cfg = copy.deepcopy(cfg)
    moved_cfg = copy.deepcopy(cfg)
    baseline_dir = root / "panel_at_baseline"
    moved_dir = root / "panel_moved"
    baseline = _run_case(rt, mi, baseline_cfg, baseline_dir, panel_center_x=baseline_x)
    moved = _run_case(rt, mi, moved_cfg, moved_dir, panel_center_x=moved_x)
    baseline_db = 10.0 * np.log10(np.maximum(baseline["map_values"], 1e-15))
    moved_db = 10.0 * np.log10(np.maximum(moved["map_values"], 1e-15))
    delta_db = moved_db - baseline_db
    np.save(root / "radio_map_delta_db.npy", delta_db)
    threshold = 1.0
    details = {
        "change": "Only the panel center x-coordinate changed.",
        "baseline_panel_center_x_m": baseline_x,
        "moved_panel_center_x_m": moved_x,
        "panel_displacement_m": moved_x - baseline_x,
        "unchanged": ["room bounds", "materials", "frequency", "transmitter", "receivers", "solver settings", "radio-map grid"],
        "difference_quantity": "moved minus baseline 10*log10(path_gain); values below 1e-15 are floored only for this display comparison",
        "mean_absolute_delta_db": float(np.mean(np.abs(delta_db))),
        "max_absolute_delta_db": float(np.max(np.abs(delta_db))),
        "cells_with_absolute_delta_over_1_db": int(np.count_nonzero(np.abs(delta_db) > threshold)),
        "cell_count": int(delta_db.size),
    }
    (root / "comparison.json").write_text(json.dumps(details, indent=2), encoding="utf-8")
    viewer_data = {
        "scenario": "comparison",
        "description": comparison["description"],
        "frequency_hz": float(cfg["frequency_hz"]),
        "baseline": json.loads((baseline_dir / "viewer_data.json").read_text(encoding="utf-8")),
        "moved": json.loads((moved_dir / "viewer_data.json").read_text(encoding="utf-8")),
        "delta_db": delta_db.tolist(),
        "comparison_stats": details,
    }
    (root / "viewer_data.json").write_text(json.dumps(viewer_data), encoding="utf-8")

    fig, axes = plt.subplots(1, 3, figsize=(15, 4.8), constrained_layout=True)
    x_len, y_len = map(float, cfg["radio_map"]["size_m"])
    cx, cy, _ = map(float, cfg["radio_map"]["center_m"])
    extent = [cx - x_len / 2.0, cx + x_len / 2.0, cy - y_len / 2.0, cy + y_len / 2.0]
    for ax, data, title in zip(axes[:2], [baseline_db, moved_db], ["Baseline", "Panel moved"]):
        im = ax.imshow(data, origin="lower", extent=extent, aspect="equal", cmap="viridis")
        ax.set_title(title)
        ax.set_xlabel("x (m)")
        ax.set_ylabel("y (m)")
    fig.colorbar(im, ax=axes[:2], label="10 log10(path gain) (dB)", shrink=0.86)
    max_delta = max(float(np.max(np.abs(delta_db))), 1.0)
    diff_im = axes[2].imshow(delta_db, origin="lower", extent=extent, aspect="equal",
                             cmap="coolwarm", vmin=-max_delta, vmax=max_delta)
    axes[2].set_title("Moved − baseline")
    axes[2].set_xlabel("x (m)")
    axes[2].set_ylabel("y (m)")
    fig.colorbar(diff_im, ax=axes[2], label="Δ path gain (dB)", shrink=0.86)
    fig.suptitle(f"Controlled panel shift: {baseline_x:.2f} m → {moved_x:.2f} m")
    fig.savefig(root / "radio_map_comparison.png", dpi=170)
    plt.close(fig)
    assert baseline["map_values"].shape == moved["map_values"].shape, "Comparison grids differ"
    assert np.any(np.abs(delta_db) > 1e-6), "The requested geometry change produced no map change"
    print(f"Comparison OK: panel shifted {moved_x - baseline_x:.2f} m; "
          f"mean absolute delta={details['mean_absolute_delta_db']:.3f} dB.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["basic", "room", "compare", "all", "view",
                                            "cea", "cea-empty", "cea-narrow", "cea-wide",
                                            "canopy-physics", "vertical-farm", "slab-test"],
                        help="PoC run to execute")
    parser.add_argument("--profile", help="vertical-farm run profile from config/vertical_farm.yaml, e.g. spark")
    args = parser.parse_args()
    if args.profile and args.command != "vertical-farm":
        parser.error("--profile only applies to the vertical-farm command")
    if args.command == "view":
        from server.viewer_server import serve  # noqa: PLC0415
        serve(ROOT)
    elif args.command == "basic":
        run_basic()
    elif args.command == "room":
        run_room()
    elif args.command == "compare":
        run_comparison()
    elif args.command.startswith("cea"):
        from demos.cea_demo import run_cea  # noqa: PLC0415
        run_cea(None if args.command == "cea" else args.command.removeprefix("cea-"))
    elif args.command == "canopy-physics":
        from demos.canopy_physics import run_canopy_physics  # noqa: PLC0415
        run_canopy_physics()
    elif args.command == "vertical-farm":
        from demos.vertical_farm import run_vertical_farm  # noqa: PLC0415
        run_vertical_farm(args.profile)
    elif args.command == "slab-test":
        from demos.slab_test import run_slab_test  # noqa: PLC0415
        run_slab_test()
    else:
        run_basic()
        run_room()
        run_comparison()


if __name__ == "__main__":
    main()
