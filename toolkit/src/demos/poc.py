def _run_case(rt, mi, cfg, output_dir: Path, panel_center_x: float | None = None):
    output_dir.mkdir(parents=True, exist_ok=True)
    scene, geometry, material_description = _build_scene(
        rt, mi, cfg, output_dir, panel_center_x=panel_center_x)
    _plot_scene(cfg, geometry, output_dir / "scene.png")
    path_cfg = cfg["path_solver"]
    path_solver = rt.PathSolver(deterministic=True)
    paths = path_solver(
        scene,
        max_depth=int(path_cfg["max_depth"]),
        samples_per_src=int(path_cfg["samples_per_source"]),
        seed=int(path_cfg["seed"]),
        los=bool(path_cfg["los"]),
        specular_reflection=bool(path_cfg["specular_reflection"]),
        diffuse_reflection=bool(path_cfg["diffuse_reflection"]),
        refraction=bool(path_cfg["refraction"]),
        diffraction=bool(path_cfg["diffraction"]),
    )
    path_summary = _save_paths(paths, cfg, output_dir)

    map_cfg = cfg["radio_map"]
    radio_map = rt.RadioMapSolver()(
        scene,
        center=mi.Point3f(map_cfg["center_m"]),
        orientation=mi.Point3f(map_cfg["orientation_rad"]),
        size=mi.Point2f(map_cfg["size_m"]),
        cell_size=mi.Point2f(map_cfg["cell_size_m"]),
        samples_per_tx=int(map_cfg["samples_per_transmitter"]),
        max_depth=int(map_cfg["max_depth"]),
        los=True,
        specular_reflection=True,
        diffuse_reflection=False,
        refraction=False,
        diffraction=False,
        seed=int(map_cfg["seed"]),
    )
    map_values, map_metadata = _save_radio_map(radio_map, cfg, output_dir)
    _write_metadata(mi, cfg, output_dir, material_description,
                    path_summary, map_metadata, panel_center_x=panel_center_x)
    _write_viewer_data(cfg, output_dir, geometry, path_summary,
                       map_values, map_metadata, panel_center_x=panel_center_x)
    return {"map_values": map_values, "path_summary": path_summary,
            "map_metadata": map_metadata}


