def _write_obj(path: Path, vertices: list[tuple[float, float, float]],
               faces: list[tuple[int, ...]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write("# Generated by the Sionna RT PoC; units are meters.\n")
        for x, y, z in vertices:
            handle.write(f"v {x:.9g} {y:.9g} {z:.9g}\n")
        for face in faces:
            handle.write("f " + " ".join(str(index) for index in face) + "\n")


def _quad_mesh(path: Path,
               quads: list[list[tuple[float, float, float]]]) -> None:
    vertices: list[tuple[float, float, float]] = []
    faces: list[tuple[int, ...]] = []
    for quad in quads:
        start = len(vertices) + 1
        vertices.extend(quad)
        faces.append((start, start + 1, start + 2, start + 3))
    _write_obj(path, vertices, faces)


def _room_geometry(room: dict[str, Any], panel_center_x: float):
    length, width, height = map(float, room["size_m"])
    panel = room["panel"]
    x0 = panel_center_x - float(panel["thickness_x_m"]) / 2.0
    x1 = panel_center_x + float(panel["thickness_x_m"]) / 2.0
    y0, y1 = map(float, panel["y_bounds_m"])
    z0, z1 = map(float, panel["z_bounds_m"])
    geometry = {
        "floor": [[(0, 0, 0), (length, 0, 0), (length, width, 0), (0, width, 0)]],
        "walls": [
            # Normals point into the room.
            [(0, 0, 0), (0, width, 0), (0, width, height), (0, 0, height)],
            [(length, 0, 0), (length, 0, height), (length, width, height), (length, width, 0)],
            [(0, 0, 0), (0, 0, height), (length, 0, height), (length, 0, 0)],
            [(0, width, 0), (length, width, 0), (length, width, height), (0, width, height)],
        ],
        "panel": [
            [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0)],
            [(x0, y0, z1), (x0, y1, z1), (x1, y1, z1), (x1, y0, z1)],
            [(x0, y0, z0), (x0, y0, z1), (x1, y0, z1), (x1, y0, z0)],
            [(x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)],
            [(x0, y0, z0), (x0, y1, z0), (x0, y1, z1), (x0, y0, z1)],
            [(x1, y0, z0), (x1, y0, z1), (x1, y1, z1), (x1, y1, z0)],
        ],
    }
    return geometry


def _build_scene(rt, mi, cfg, output_dir: Path, panel_center_x: float | None = None):
    is_basic = cfg["scenario"] == "basic_demo"
    if is_basic:
        scene = rt.load_scene(rt.scene.floor_wall)
        geometry = {
            "floor": [[(-2, -2, 0), (2, -2, 0), (2, 2, 0), (-2, 2, 0)]],
            "walls": [[(0, -1.75, 0.9), (0, 1.75, 0.9),
                       (0, 1.75, 2.9), (0, -1.75, 2.9)]],
            "panel": [],
        }
        materials_description = {
            "floor": "Sionna built-in ITU concrete material",
            "wall": "Sionna built-in ITU brick material",
        }
    else:
        scene = rt.load_scene()
        room = cfg["room"]
        if panel_center_x is None:
            panel_center_x = float(room["panel"]["center_x_m"])
        geometry = _room_geometry(room, panel_center_x)
        material_cfg = cfg["materials"]
        concrete = rt.RadioMaterial(
            name="generic_concrete_like",
            relative_permittivity=float(material_cfg["concrete_like"]["relative_permittivity"]),
            conductivity=float(material_cfg["concrete_like"]["conductivity_s_per_m"]),
            scattering_coefficient=0.0,
            color=tuple(material_cfg["concrete_like"]["color_rgb"]),
        )
        panel_mat = rt.RadioMaterial(
            name="generic_panel_like",
            relative_permittivity=float(material_cfg["panel_like"]["relative_permittivity"]),
            conductivity=float(material_cfg["panel_like"]["conductivity_s_per_m"]),
            scattering_coefficient=0.0,
            color=tuple(material_cfg["panel_like"]["color_rgb"]),
        )
        asset_dir = output_dir / "generated_meshes"
        floor_path = asset_dir / "room_floor.obj"
        walls_path = asset_dir / "room_walls.obj"
        panel_path = asset_dir / "panel.obj"
        _quad_mesh(floor_path, geometry["floor"])
        _quad_mesh(walls_path, geometry["walls"])
        _quad_mesh(panel_path, geometry["panel"])
        scene.add([concrete, panel_mat])
        scene.add([
            rt.SceneObject(fname=str(floor_path), name="room_floor",
                           radio_material=concrete, remove_duplicate_vertices=True),
            rt.SceneObject(fname=str(walls_path), name="room_walls",
                           radio_material=concrete, remove_duplicate_vertices=True),
            rt.SceneObject(fname=str(panel_path), name="movable_panel",
                           radio_material=panel_mat, remove_duplicate_vertices=True),
        ])
        materials_description = {
            "concrete_like": material_cfg["concrete_like"],
            "panel_like": material_cfg["panel_like"],
            "note": "Illustrative placeholders; not validated against a real site.",
        }

    scene.frequency = float(cfg["frequency_hz"])
    array_cfg = cfg["antenna"]
    def make_array():
        return rt.PlanarArray(
            num_rows=int(array_cfg["rows"]),
            num_cols=int(array_cfg["columns"]),
            pattern=array_cfg["pattern"],
            polarization=array_cfg["polarization"],
        )
    scene.tx_array = make_array()
    scene.rx_array = make_array()
    tx_cfg = cfg["transmitter"]
    tx = rt.Transmitter(
        name=tx_cfg["name"],
        position=mi.Point3f(tx_cfg["position_m"]),
        power_dbm=float(tx_cfg["power_dbm"]),
        color=(0.9, 0.12, 0.12),
        display_radius=0.18,
    )
    receivers = [
        rt.Receiver(name=item["name"],
                    position=mi.Point3f(item["position_m"]),
                    color=(0.08, 0.48, 0.18), display_radius=0.14)
        for item in cfg["receivers"]
    ]
    scene.add([tx, *receivers])
    return scene, geometry, materials_description


def _plot_scene(cfg, geometry, output_file: Path):
    fig = plt.figure(figsize=(9, 6.3))
    ax = fig.add_subplot(111, projection="3d")
    if cfg["scenario"] == "basic_demo":
        x0, x1, y0, y1, z0, z1 = -2, 2, -2, 2, 0, 3
    else:
        x0, x1 = 0, float(cfg["room"]["size_m"][0])
        y0, y1 = 0, float(cfg["room"]["size_m"][1])
        z0, z1 = 0, float(cfg["room"]["size_m"][2])

    if geometry["floor"]:
        ax.add_collection3d(Poly3DCollection(
            geometry["floor"], facecolor="#cdd4dc", edgecolor="#657383", alpha=0.28))
    if geometry["walls"]:
        ax.add_collection3d(Poly3DCollection(
            geometry["walls"], facecolor="#6b879f", edgecolor="#38536c", alpha=0.22))
    if geometry["panel"]:
        ax.add_collection3d(Poly3DCollection(
            geometry["panel"], facecolor="#e78a42", edgecolor="#a84f14", alpha=0.62))

    tx = cfg["transmitter"]
    tx_pos = tx["position_m"]
    ax.scatter(*tx_pos, c="#d52222", marker="*", s=150, label=tx["name"])
    ax.text(*tx_pos, f"  {tx['name']}", color="#8a1111")
    for rx in cfg["receivers"]:
        pos = rx["position_m"]
        ax.scatter(*pos, c="#18833a", marker="o", s=45, label=rx["name"])
        ax.text(*pos, f"  {rx['name']}", color="#125e2d")
    ax.set_xlim(x0 - 0.2, x1 + 0.2)
    ax.set_ylim(y0 - 0.2, y1 + 0.2)
    ax.set_zlim(z0, z1 + 0.2)
    ax.set_xlabel("x (m)")
    ax.set_ylabel("y (m)")
    ax.set_zlabel("z (m), up")
    ax.set_title(f"{cfg['scenario']} geometry and radio devices")
    ax.set_box_aspect((max(x1 - x0, 1), max(y1 - y0, 1), max(z1 - z0, 1)))
    ax.view_init(elev=23, azim=-58)
    handles, labels = ax.get_legend_handles_labels()
    by_label = dict(zip(labels, handles))
    ax.legend(by_label.values(), by_label.keys(), loc="upper left", fontsize=8)
    fig.tight_layout()
    output_file.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_file, dpi=170, bbox_inches="tight")
    plt.close(fig)


def _save_paths(paths, cfg, output_dir: Path, object_id_to_name: dict[int, str] | None = None,
                allow_empty: bool = False):
    a_complex, tau = paths.cir(normalize_delays=False, out_type="numpy")
    a_complex = np.asarray(a_complex)
    a_re = a_complex.real
    a_im = a_complex.imag
    tau = np.asarray(tau)
    valid = _tensor_numpy(paths.valid).astype(bool, copy=False)
    interaction_types = _tensor_numpy(paths.interactions).astype(np.uint32, copy=False)
    interaction_objects = _tensor_numpy(paths.objects).astype(np.uint32, copy=False)
    interaction_vertices = _tensor_numpy(paths.vertices).astype(np.float64, copy=False)
    object_id_to_name = object_id_to_name or {}
    receiver_count = len(cfg["receivers"])
    assert a_re.shape[0] == receiver_count, f"CIR has {a_re.shape[0]} RX entries, expected {receiver_count}"
    assert tau.shape[0] == receiver_count, f"Delay tensor has {tau.shape[0]} RX entries"

    rows = []
    per_receiver = []
    for rx_index, rx in enumerate(cfg["receivers"]):
        coeff = a_complex[rx_index]
        while coeff.ndim > 2:
            coeff = coeff[0]
        if coeff.ndim != 2:
            raise ValueError(f"Unexpected CIR coefficient layout: {a_complex.shape}")
        coeff_re = coeff[:, 0].real
        coeff_im = coeff[:, 0].imag
        delays = tau[rx_index]
        while delays.ndim > 1:
            delays = delays[0]
        mask = valid[rx_index]
        while mask.ndim > 1:
            mask = mask[0]
        rx_types = interaction_types[:, rx_index]
        rx_objects = interaction_objects[:, rx_index]
        rx_vertices = interaction_vertices[:, rx_index]
        while rx_types.ndim > 2:
            rx_types = rx_types[:, 0]
        while rx_objects.ndim > 2:
            rx_objects = rx_objects[:, 0]
        while rx_vertices.ndim > 3:
            rx_vertices = rx_vertices[:, 0]
        assert coeff_re.size == delays.size == mask.size, (
            f"Path dimensions disagree for {rx['name']}: "
            f"coeff={coeff_re.size}, delays={delays.size}, valid={mask.size}"
        )
        receiver_rows = []
        for path_index in np.flatnonzero(mask):
            magnitude = float(np.hypot(coeff_re[path_index], coeff_im[path_index]))
            type_ids = [int(value) for value in rx_types[:, path_index] if int(value) != 0]
            object_ids = [int(value) for value in rx_objects[:, path_index]
                          if int(value) != np.iinfo(np.uint32).max]
            names = {1: "specular_reflection", 2: "diffuse_reflection", 4: "refraction",
                     8: "diffraction", 16: "sensing"}
            row = {
                "receiver": rx["name"],
                "path_index": int(path_index),
                "delay_s": float(delays[path_index]),
                "delay_ns": float(delays[path_index] * 1e9),
                "path_length_m_from_delay": float(delays[path_index] * 299_792_458.0),
                "a_real": float(coeff_re[path_index]),
                "a_imag": float(coeff_im[path_index]),
                "magnitude": magnitude,
                "magnitude_db": float(20.0 * np.log10(max(magnitude, 1e-30))),
                "interaction_type_ids": type_ids,
                "interaction_types": [names.get(value, f"interaction_{value}") for value in type_ids],
                "interacted_objects": [object_id_to_name.get(value, f"object_id_{value}")
                                       for value in object_ids],
                "interaction_vertices_m": rx_vertices[:len(type_ids), path_index].tolist(),
                "is_los": len(type_ids) == 0,
            }
            rows.append(row)
            receiver_rows.append(row)
        per_receiver.append({"receiver": rx["name"], "valid_path_count": len(receiver_rows)})
    if not allow_empty:
        assert sum(item["valid_path_count"] for item in per_receiver) > 0, "PathSolver returned no valid paths"

    with (output_dir / "cir.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=[
            "receiver", "path_index", "delay_s", "delay_ns", "path_length_m_from_delay",
            "a_real", "a_imag", "magnitude", "magnitude_db",
            "interaction_type_ids", "interaction_types", "interacted_objects",
            "interaction_vertices_m", "is_los",
        ])
        writer.writeheader()
        writer.writerows(rows)
    path_summary = {
        "description": "Valid Sionna paths and baseband-equivalent CIR coefficients; no RSS conversion applied.",
        "cir_shape": list(a_re.shape),
        "delay_shape": list(tau.shape),
        "valid_shape": list(valid.shape),
        "receivers": per_receiver,
        "paths": rows,
    }
    (output_dir / "paths.json").write_text(json.dumps(path_summary, indent=2), encoding="utf-8")

    fig, ax = plt.subplots(figsize=(8.6, 4.6))
    for rx in cfg["receivers"]:
        selected = [row for row in rows if row["receiver"] == rx["name"]]
        if selected:
            ax.scatter([row["delay_s"] * 1e9 for row in selected],
                       [row["magnitude_db"] for row in selected],
                       label=rx["name"], s=35, alpha=0.8)
    ax.set_xlabel("Excess-inclusive path delay (ns)")
    ax.set_ylabel("CIR coefficient magnitude (dB re 1)")
    ax.set_title("Sionna RT path coefficients by receiver")
    ax.grid(True, alpha=0.25)
    if rows:
        ax.legend()
    fig.tight_layout()
    fig.savefig(output_dir / "cir.png", dpi=170)
    plt.close(fig)
    return path_summary


def _map_array(radio_map):
    raw = _tensor_numpy(radio_map.path_gain).astype(np.float64, copy=False)
    assert raw.ndim >= 2, f"Unexpected radio-map shape: {raw.shape}"
    assert raw.shape[0] == 1, f"This PoC expects one transmitter, got shape {raw.shape}"
    values = np.squeeze(raw[0])
    assert values.ndim == 2, f"Expected a 2-D single-TX planar map, got {values.shape}"
    assert np.isfinite(values).all(), "Radio map contains NaN or infinite values"
    assert np.any(values > 0), "Radio map contains no positive path gain"
    return raw, values


def _save_radio_map(radio_map, cfg, output_dir: Path):
    raw, values = _map_array(radio_map)
    np.save(output_dir / "radio_map.npy", raw)
    cell_centers = _tensor_numpy(radio_map.cell_centers)
    np.save(output_dir / "radio_map_cell_centers.npy", cell_centers)
    linear_floor = 1e-15
    values_db = 10.0 * np.log10(np.maximum(values, linear_floor))
    np.save(output_dir / "radio_map_db.npy", values_db)
    map_cfg = cfg["radio_map"]
    metadata = {
        "quantity": "path_gain",
        "units": "linear power ratio (unitless); not RSS or received power",
        "display_transform": "10*log10(max(path_gain, 1e-15)) dB, for plotting only",
        "raw_array_file": "radio_map.npy",
        "raw_array_shape": list(raw.shape),
        "raw_array_axes": ["transmitter", "y_cell", "x_cell"],
        "plotted_array_shape": list(values.shape),
        "cell_centers_file": "radio_map_cell_centers.npy",
        "cell_centers_shape": list(cell_centers.shape),
        "frequency_hz": float(cfg["frequency_hz"]),
        "center_m": map_cfg["center_m"],
        "orientation_rad": map_cfg["orientation_rad"],
        "requested_size_m": map_cfg["size_m"],
        "cell_size_m": map_cfg["cell_size_m"],
        "grid_x_cells": int(values.shape[1]),
        "grid_y_cells": int(values.shape[0]),
        "positive_cell_count": int(np.count_nonzero(values > 0)),
        "min_positive_path_gain_linear": float(np.min(values[values > 0])),
        "max_path_gain_linear": float(np.max(values)),
    }
    (output_dir / "radio_map_metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    x_len, y_len = map(float, map_cfg["size_m"])
    cx, cy, _ = map(float, map_cfg["center_m"])
    extent = [cx - x_len / 2.0, cx + x_len / 2.0,
              cy - y_len / 2.0, cy + y_len / 2.0]
    fig, ax = plt.subplots(figsize=(8.6, 5.4))
    im = ax.imshow(values_db, origin="lower", extent=extent, aspect="equal", cmap="viridis")
    ax.set_xlabel("x (m)")
    ax.set_ylabel("y (m)")
    ax.set_title("Path gain (dB; plotted from linear ratio)")
    fig.colorbar(im, ax=ax, label="10 log10(path gain) (dB)")
    fig.tight_layout()
    fig.savefig(output_dir / "radio_map.png", dpi=170)
    plt.close(fig)
    return values, metadata


