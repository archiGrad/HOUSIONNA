"""Case study of the paper in one command: applications, placement, maps, and the LaTeX tables.

    python run.py casestudy --batch <batch> [--run <multi-TX run>] [--k 3]

Runs `apps` on every imported run of the batch and, with --run, `placement` and `maps` (all transmitters and the
best k) on one run with several candidate transmitters, for each harvester (default: the measured sensor, the
high-power rectifier path it uses, and the low-power path). It then collects the numbers the paper reports into
outputs/casestudy/<batch>/: casestudy_numbers.json, casestudy_tables.tex (tables to paste into Overleaf) and
figures.txt (the figure files to upload).
"""
from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path
import statistics
from typing import Any

from engine.application_engine import ROOT, WPT_STRATEGIES, _jsonable, load_config, main as apps_main
from engine.application_maps import MAP_STRATEGIES, main as maps_main
from engine.placement import main as placement_main

HARVESTERS = ("cappelle2025_chain", "rectifier_bound_915", "rectifier_low_915")
HARVESTER_LABELS = {"cappelle2025_chain": "Sensor (measured)", "rectifier_bound_915": "Rectifier, high-power path",
                    "rectifier_low_915": "Rectifier, low-power path"}
HARVESTER_COLUMNS = {"cappelle2025_chain": "Sensor", "rectifier_bound_915": "High path", "rectifier_low_915": "Low path"}
PLACEMENT_ROWS = (1, 2, 3, 5, 10)          # plus the full set of candidates
STRATEGY_LABELS = {"single_best": "Best single transmitter", "equal_incoherent": "Equal split, incoherent",
                   "equal_in_phase": "Equal split, in phase", "coherent_mrt": "Coherent MRT",
                   "coherent_mrt_mean": "Coherent MRT (local mean)"}
HOUR_S = 3600.0


def receiver_stats(per_receiver: Path, cycle: str) -> dict[str, dict[str, Any]]:
    """Per strategy: receivers whose node completes a cycle within an hour, and the median interval over all."""
    rows = list(csv.DictReader(per_receiver.open(encoding="utf-8")))
    out = {}
    for strategy in WPT_STRATEGIES:
        intervals = [float(row[f"wpt_{strategy}_{cycle}_interval_s"]) for row in rows]
        median = statistics.median(intervals) if intervals else math.inf
        out[strategy] = {"receivers": len(intervals),
                         "within_hour": sum(value <= HOUR_S for value in intervals),
                         "median_interval_s": median}
    return out


def _share(value: float) -> str:
    return f"{100 * value:.0f}\\,\\%"


def _interval(seconds: float) -> str:
    if not math.isfinite(seconds):
        return "--"
    if seconds < HOUR_S:
        return f"{seconds / 60:.0f}\\,min"
    if seconds < 48 * HOUR_S:
        return f"{seconds / HOUR_S:.1f}\\,h"
    return f"{seconds / 86400:.0f}\\,d"


def _tex(text: str) -> str:
    return str(text).replace("_", "\\_")


def latex_tables(numbers: dict[str, Any]) -> str:
    harvesters = numbers["harvesters"]
    head = " & ".join(HARVESTER_COLUMNS.get(h, _tex(h)) for h in harvesters)
    columns = "; ".join(f"{HARVESTER_COLUMNS.get(h, _tex(h))}: {HARVESTER_LABELS.get(h, _tex(h)).lower()}"
                        for h in harvesters)
    lines = ["% Generated by python run.py casestudy; paste into the case-study section.", "",
             "\\begin{table}[t]",
             f"\\caption{{RF power transfer to the plant sensor over the {numbers['receivers']} receivers of batch "
             f"{_tex(numbers['batch'])}: share of receivers whose node completes a {numbers['cycle_mj']:g}\\,mJ "
             f"cycle within one hour, with the median reporting interval in brackets ({columns}).}}",
             "\\label{tab:cs_wpt}", "\\centering\\footnotesize",
             "\\begin{tabular}{@{}l" + "c" * len(harvesters) + "@{}}", "\\toprule",
             f"Strategy & {head} \\\\", "\\midrule"]
    for strategy in WPT_STRATEGIES:
        cells = []
        for harvester in harvesters:
            item = numbers["receivers_by_harvester"][harvester][strategy]
            cells.append(f"{_share(item['within_hour'] / item['receivers'])} ({_interval(item['median_interval_s'])})")
        lines.append(f"{STRATEGY_LABELS[strategy]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    if numbers.get("maps"):
        lines += ["\\begin{table}[t]",
                  f"\\caption{{Share of the radio-map area of run {_tex(numbers['run'])} where the node completes a "
                  f"cycle within one hour, with all {numbers['candidates']} transmitters and with the best "
                  f"{numbers['k']}.}}",
                  "\\label{tab:cs_maps}", "\\centering\\footnotesize",
                  "\\begin{tabular}{@{}l" + "c" * len(harvesters) + "@{}}", "\\toprule",
                  f"Strategy & {head} \\\\", "\\midrule"]
        for strategy in MAP_STRATEGIES:
            cells = []
            for harvester in harvesters:
                every, best = (numbers["maps"][harvester][tag][strategy] for tag in ("all", f"k{numbers['k']}"))
                cells.append(f"{_share(every)} / {_share(best)}")
            lines.append(f"{STRATEGY_LABELS[strategy]} & " + " & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    if numbers.get("placement"):
        lines += ["\\begin{table}[t]",
                  "\\caption{Transmitter placement: value at the worst receiver for the best subset of $k$ "
                  "candidates and the median over all subsets of that size.}",
                  "\\label{tab:cs_placement}", "\\centering\\footnotesize",
                  "\\begin{tabular}{@{}rcc@{}}", "\\toprule",
                  "$k$ & BLE margin (dB) & Coherent \\gls{wpt} power (dBm) \\\\",
                  "& best / median & best / median \\\\", "\\midrule"]
        shown = set(PLACEMENT_ROWS) | {numbers["candidates"]}
        for row in (row for row in numbers["placement"] if row["k"] in shown):
            cells = [f"{row[key]:.1f}".replace("-", "$-$") for key in ("ble_best", "ble_median", "wpt_best", "wpt_median")]
            lines.append(f"{row['k']} & {cells[0]} / {cells[1]} & {cells[2]} / {cells[3]} \\\\")
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="run.py casestudy", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--batch", required=True, help="batch whose imported runs give the receiver statistics")
    parser.add_argument("--run", help="run with several candidate transmitters, for placement and maps")
    parser.add_argument("--k", type=int, default=3, help="number of transmitters for the best-k map (default 3)")
    parser.add_argument("--harvester", action="append", help=f"harvester (repeatable; default {', '.join(HARVESTERS)})")
    parser.add_argument("--cycle", default="case_I_imu_ble_basic", help="energy cycle from wpt.cycles_j")
    args = parser.parse_args(argv)
    harvesters = args.harvester or list(HARVESTERS)
    config = load_config()
    out = ROOT / "outputs" / "casestudy" / args.batch
    out.mkdir(parents=True, exist_ok=True)
    figures: list[Path] = []

    numbers: dict[str, Any] = {"batch": args.batch, "harvesters": harvesters, "cycle": args.cycle,
                               "cycle_mj": 1e3 * float(config["wpt"]["cycles_j"][args.cycle]),
                               "total_power_dbm": config["wpt"]["total_power_dbm"], "receivers_by_harvester": {}}
    for harvester in harvesters:
        print(f"== apps, {harvester}")
        if apps_main(["--batch", args.batch, "--harvester", harvester]):
            return 2
        folder = ROOT / "outputs" / "applications" / f"{args.batch}_{harvester}"
        numbers["receivers_by_harvester"][harvester] = receiver_stats(folder / "per_receiver.csv", args.cycle)
        figures.append(folder / "wpt_rf_power_cdf.pdf")
        if "communication" not in numbers:
            summary = json.loads((folder / "summary.json").read_text(encoding="utf-8"))
            numbers["communication_worst_margin_db"] = summary["worst_case_over_runs"]
            numbers["runs"] = len(summary["runs"])
            numbers["frequency_hz"] = sorted({run["frequency_hz"] for run in summary["runs"]})
    numbers["receivers"] = next(iter(numbers["receivers_by_harvester"].values()))["coherent_mrt"]["receivers"]

    if args.run:
        print(f"== placement, {args.run}")
        if placement_main(["--run", args.run]):
            return 2
        folder = ROOT / "outputs" / "placement" / args.run.replace(".", "_")
        placement = json.loads((folder / "placement.json").read_text(encoding="utf-8"))
        key = "best_value" if placement["exhaustive"] else "greedy_value"
        numbers.update(run=args.run, candidates=len(placement["candidates"]), k=args.k)
        numbers["placement"] = [{"k": row["k"],
                                 "ble_best": row["objectives"]["ble_margin"][key],
                                 "ble_median": row["objectives"]["ble_margin"].get("median", math.nan),
                                 "wpt_best": row["objectives"]["wpt_coherent"][key],
                                 "wpt_median": row["objectives"]["wpt_coherent"].get("median", math.nan)}
                                for row in placement["sizes"]]
        figures += [folder / "placement_vs_k.pdf"]
        numbers["maps"] = {}
        for harvester in harvesters:
            numbers["maps"][harvester] = {}
            for tag, extra in (("all", []), (f"k{args.k}", ["--placement-k", str(args.k)])):
                print(f"== maps {tag}, {harvester}")
                if maps_main(["--run", args.run, "--harvester", harvester, *extra]):
                    return 2
                maps_folder = ROOT / "outputs" / "applications" / "maps" / args.run.replace(".", "_")
                summary = json.loads((maps_folder / f"maps_{tag}_{harvester}.json").read_text(encoding="utf-8"))
                numbers["maps"][harvester][tag] = {strategy: item["area_share_within_s"][str(int(HOUR_S))]
                                                   for strategy, item in summary["wpt"].items()}
                figures.append(maps_folder / f"map_interval_{tag}_{harvester}.pdf")

    (out / "casestudy_numbers.json").write_text(json.dumps(_jsonable(numbers), indent=2), encoding="utf-8")
    (out / "casestudy_tables.tex").write_text(latex_tables(numbers), encoding="utf-8")
    (out / "figures.txt").write_text("\n".join(str(p.relative_to(ROOT)) for p in figures if p.is_file()) + "\n",
                                     encoding="utf-8")
    print(f"\nBLE worst margin {numbers['communication_worst_margin_db']['ble_1m']:.1f} dB, "
          f"LoRa {numbers['communication_worst_margin_db']['lora_sf7_125k']:.1f} dB over {numbers['runs']} runs "
          f"at {', '.join(f'{f / 1e9:g} GHz' for f in numbers['frequency_hz'])}")
    for harvester in harvesters:
        mrt = numbers["receivers_by_harvester"][harvester]["coherent_mrt"]
        print(f"{HARVESTER_LABELS.get(harvester, harvester)}: coherent MRT, {mrt['within_hour']}/{mrt['receivers']} "
              f"receivers within 1 h, median interval {_interval(mrt['median_interval_s']).replace(chr(92) + ',', ' ')}")
    print("written:", ", ".join(str((out / name).relative_to(ROOT))
                                for name in ("casestudy_numbers.json", "casestudy_tables.tex", "figures.txt")))
    return 0
